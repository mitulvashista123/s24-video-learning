#!/usr/bin/env bash
# CI step of the GitOps loop:
#   1. build every service image and push it to ECR (tag = short git SHA)
#   2. regenerate k8s-apps/overlays/aws/kustomization.yaml with the new image pins
#   3. commit + push -> ArgoCD notices the Git change and rolls the cluster forward.
# No kubectl apply is ever used for application workloads.
#
# Usage: scripts/build-and-push.sh [--no-push-git] [service ...]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PUSH_GIT=1
if [[ "${1:-}" == "--no-push-git" ]]; then PUSH_GIT=0; shift; fi

ALL_SERVICES=(user-service catalog-service metadata-service content-delivery-api cache-manager progress-tracker)
if [[ $# -gt 0 ]]; then SERVICES=("$@"); else SERVICES=("${ALL_SERVICES[@]}"); fi

REGION="$(terraform -chdir=terraform output -raw aws_region)"
REGISTRY="$(terraform -chdir=terraform output -raw ecr_registry)"
PROJECT="$(terraform -chdir=terraform output -json ecr_repositories | python3 -c 'import json,sys; r=json.load(sys.stdin); print(next(iter(r.values())).split("/")[1])')"
TAG="$(git rev-parse --short HEAD)-$(date +%Y%m%d%H%M%S)"

echo ">> logging in to ${REGISTRY}"
aws ecr get-login-password --region "$REGION" | docker login --username AWS --password-stdin "$REGISTRY"

for svc in "${SERVICES[@]}"; do
  image="${REGISTRY}/${PROJECT}/${svc}"
  echo ">> building ${svc} -> ${image}:${TAG}"
  docker build --platform linux/amd64 -f "services/${svc}/Dockerfile" -t "${image}:${TAG}" -t "${image}:latest" services
  docker push "${image}:${TAG}"
  docker push "${image}:latest"
done

OVERLAY="k8s-apps/overlays/aws/kustomization.yaml"
python3 - "$OVERLAY" "$REGISTRY" "$PROJECT" "$TAG" "${SERVICES[@]}" <<'PY'
import os, re, sys
path, registry, project, tag, *built = sys.argv[1:]
services = ["user-service", "catalog-service", "metadata-service",
            "content-delivery-api", "cache-manager", "progress-tracker"]
current = {}
if os.path.exists(path):
    for name, new_tag in re.findall(r"- name: s24/([\w-]+)\n\s+newName: [^\n]+\n\s+newTag: \"?([^\"\n]+)\"?", open(path).read()):
        current[name] = new_tag
lines = [
    "# Generated by scripts/build-and-push.sh – ArgoCD syncs this overlay.",
    "apiVersion: kustomize.config.k8s.io/v1beta1",
    "kind: Kustomization",
    "resources:",
    "  - ../../base",
    "images:",
]
for svc in services:
    lines += [f"  - name: s24/{svc}",
              f"    newName: {registry}/{project}/{svc}",
              f'    newTag: "{tag if svc in built or svc not in current else current[svc]}"']
open(path, "w").write("\n".join(lines) + "\n")
print(f"updated {path}")
PY

# keep argocd-app.yaml pointing at this repository
REMOTE="$(git remote get-url origin 2>/dev/null || true)"
if [[ -n "$REMOTE" ]]; then
  REMOTE_HTTPS="$(echo "$REMOTE" | sed -E 's#^git@([^:]+):#https://\1/#')"
  sed -i.bak -E "s#^(    repoURL: ).*#\1${REMOTE_HTTPS}#" argocd-app.yaml && rm -f argocd-app.yaml.bak
fi

if [[ $PUSH_GIT -eq 1 ]]; then
  git add "$OVERLAY" argocd-app.yaml
  git commit -m "deploy: ${SERVICES[*]} @ ${TAG}" || echo "nothing to commit"
  git push
  echo ">> pushed; ArgoCD will sync within ~60s (argocd app get s24-services)"
fi
